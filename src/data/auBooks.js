// Helper function to get AU by ID
export const getAUById = (id) => {
  return auBooks.find(au => au.id === id);
};

// Helper function to get AUs by rarity
export const getAUsByRarity = (rarity) => {
  return auBooks.filter(au => au.rarity === rarity);
};

// Roll a random AU for gacha (respects drop rates)
export const rollAU = (poolType = 'normal') => {
  const rand = Math.random() * 100;
  let rarity;

  if (poolType === 'normal') {
    // Normal pool: 70% common, 20% rare, 8% super, 2% ultra
    if (rand < 70) rarity = 'common';
    else if (rand < 90) rarity = 'rare';
    else if (rand < 98) rarity = 'super';
    else rarity = 'ultra';
  } else {
    // Spicy pool: 20% common, 40% rare, 30% super, 10% ultra
    if (rand < 20) rarity = 'common';
    else if (rand < 60) rarity = 'rare';
    else if (rand < 90) rarity = 'super';
    else rarity = 'ultra';
  }

  const ausOfRarity = auBooks.filter(au => au.rarity === rarity);
  return ausOfRarity[Math.floor(Math.random() * ausOfRarity.length)];
};
